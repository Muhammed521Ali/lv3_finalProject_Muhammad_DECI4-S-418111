import pandas as pd
import matplotlib.pyplot as plt

df=pd.read_csv("/content/github_projects.csv")
df['creation'] = pd.to_datetime(df['creation'])

df.head()

nstarsn = df.sort_values(by="stargazers", ascending=False)

stars = nstarsn.head(10)
hjh=stars['stargazers']/1000

plt.figure(figsize=(15,15), facecolor='white')
ax = plt.gca()
ax.set_facecolor('#D4BBA1')
Barplot1=plt.bar(stars["owner"],hjh,
    color='#140d1c')
plt.xlabel("owner")
